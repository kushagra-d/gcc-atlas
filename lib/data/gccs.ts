interface Seed {
  name: string;
  parent: string;
  sector: string;
  cities: string[];
  units: number;
  band: HeadcountBand;
  fn: GccFunction[];
  loc: Prov;
  hc: Prov;
  fnp: Prov;
  date: string;
  tag?: string;
  conflict?: Gcc["conflict"];
}

const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");

const seed = (s: Seed): Gcc => ({
  id: slug(s.name),
  name: s.name,
  parent: s.parent,
  sector: s.sector,
  cities: s.cities,
  units: s.units,
  band: s.band,
  functions: s.fn,
  lastVerified: s.date,
  prov: { location: s.loc, headcount: s.hc, functions: s.fnp },
  tag: s.tag,
  conflict: s.conflict,
  origin: "seed",
});

